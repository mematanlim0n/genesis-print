-- Historial centralizado. El trigger registra usuario, fecha, operación y diferencias.
create table if not exists public.change_history (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text not null,
  action text not null,
  record_label text,
  old_data jsonb,
  new_data jsonb,
  user_id uuid,
  user_email text,
  changed_at timestamptz not null default now()
);

create or replace function public.genesis_audit_changes()
returns trigger language plpgsql security definer set search_path=public as $$
declare oldj jsonb; newj jsonb; rid text; label text;
begin
  if TG_OP='DELETE' then oldj=to_jsonb(OLD); newj=null; rid=coalesce(oldj->>'id',''); label=coalesce(oldj->>'name',oldj->>'service_name','Registro');
  elsif TG_OP='UPDATE' then oldj=to_jsonb(OLD); newj=to_jsonb(NEW); rid=coalesce(newj->>'id',''); label=coalesce(newj->>'name',newj->>'service_name','Registro');
  else oldj=null; newj=to_jsonb(NEW); rid=coalesce(newj->>'id',''); label=coalesce(newj->>'name',newj->>'service_name','Registro'); end if;
  insert into public.change_history(table_name,record_id,action,record_label,old_data,new_data,user_id,user_email)
  values(TG_TABLE_NAME,rid,TG_OP,label,oldj,newj,auth.uid(),auth.jwt()->>'email');
  if TG_OP='DELETE' then return OLD; else return NEW; end if;
end; $$;

drop trigger if exists genesis_audit_products on public.products;
create trigger genesis_audit_products after insert or update or delete on public.products for each row execute function public.genesis_audit_changes();
drop trigger if exists genesis_audit_service_prices on public.service_prices;
create trigger genesis_audit_service_prices after insert or update or delete on public.service_prices for each row execute function public.genesis_audit_changes();

-- Presupuestos guardados con sus renglones congelados como JSON para conservar el precio cotizado.
create table if not exists public.budgets (
  id bigint generated by default as identity primary key,
  budget_number text not null unique,
  customer_name text,
  notes text,
  items jsonb not null default '[]'::jsonb,
  total numeric not null default 0,
  created_by uuid default auth.uid(),
  created_by_email text default (auth.jwt()->>'email'),
  created_at timestamptz not null default now()
);

