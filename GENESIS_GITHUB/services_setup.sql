-- GENESIS: tabla independiente para servicios de impresion
create table if not exists public.service_prices (
  id bigint generated by default as identity primary key,
  category text not null,
  service_name text not null,
  option_label text,
  quantity_label text,
  bw_price numeric,
  color_price numeric,
  single_price numeric,
  double_price numeric,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.service_prices enable row level security;
drop policy if exists "Authenticated users can read service prices" on public.service_prices;
create policy "Authenticated users can read service prices" on public.service_prices for select to authenticated using (true);
drop policy if exists "Authenticated users can insert service prices" on public.service_prices;
create policy "Authenticated users can insert service prices" on public.service_prices for insert to authenticated with check (true);
drop policy if exists "Authenticated users can update service prices" on public.service_prices;
create policy "Authenticated users can update service prices" on public.service_prices for update to authenticated using (true) with check (true);

create unique index if not exists service_prices_seed_key on public.service_prices (category, service_name, coalesce(option_label, ''), coalesce(quantity_label, ''));

create or replace function public.set_service_prices_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at = now(); return new; end; $$;
drop trigger if exists set_service_prices_updated_at on public.service_prices;
create trigger set_service_prices_updated_at before update on public.service_prices for each row execute function public.set_service_prices_updated_at();

